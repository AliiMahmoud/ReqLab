function scope(name: string, what: string): [string, Kind, string][] {
  const path = `pm.${name}`;
  return [
    [path, "namespace", `Variables of ${what}`],
    [`${path}.get`, "function", "(key) → value"],
    [`${path}.set`, "function", "(key, value) saved"],
    [`${path}.unset`, "function", "(key) removed"],
    [`${path}.has`, "function", "(key) → boolean"],
    [`${path}.clear`, "function", "() removes all"],
    [`${path}.toObject`, "function", "() → all values"],
  ];
}

function headers(path: string, canChange: boolean): [string, Kind, string][] {
  const read: [string, Kind, string][] = [
    [`${path}.get`, "function", "(name) → value"],
    [`${path}.has`, "function", "(name) → boolean"],
    [`${path}.toObject`, "function", "() → all headers"],
  ];
  if (!canChange) return read;
  return [
    ...read,
    [`${path}.add`, "function", "({ key, value })"],
    [`${path}.upsert`, "function", "({ key, value }) add or replace"],
    [`${path}.remove`, "function", "(name)"],
  ];
}
